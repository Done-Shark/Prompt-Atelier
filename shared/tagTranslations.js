/** 查询内置词典；未收录返回 null */
export function lookupBuiltinTag(raw) {
  const key = normalizeTagKey(raw);
  if (!key) return null;
  const entry = ENTRIES[key];
  if (!entry) return null;
  return {
    tag: key,
    translation: entry[0],
    category: entry[1] || guessTagCategory(key),
  };
}

export function builtinTagCount() {
  return Object.keys(ENTRIES).length;
}

export function builtinTagKeys() {
  return Object.keys(ENTRIES);
}
